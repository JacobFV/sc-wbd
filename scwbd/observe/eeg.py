def pink_noise(
    shape: Sequence[int],
    dt: float,
    exponent: float = 1.0,
    *,
    seed: int,
    f_knee: float = 0.5,
    device: torch.device | str = "cpu",
    dtype: torch.dtype = torch.float64,
) -> torch.Tensor:
    """Unit-variance ``1/f**exponent`` noise along the last axis.

    Generated by spectral shaping of white noise on the *native* clock:
    ``S(f) ~ 1 / (f**2 + f_knee**2)**(exponent/2)``, which is finite at DC and
    therefore does not manufacture an unbounded drift out of a finite record.
    """
    shape = tuple(shape)
    n = shape[-1]
    g = torch.Generator(device="cpu").manual_seed(int(seed))
    w = torch.randn(shape, generator=g, dtype=torch.float64)
    W = torch.fft.rfft(w, dim=-1)
    f = torch.fft.rfftfreq(n, d=dt).to(torch.float64)
    shaping = (f**2 + f_knee**2) ** (-exponent / 2.0)
    out = torch.fft.irfft(W * shaping, n=n, dim=-1)
    sd = out.std(dim=-1, keepdim=True).clamp_min(1e-30)
    return (out / sd).to(device=device, dtype=dtype)


@dataclass(frozen=True)
class EEGNoiseModel:
    """Instrument + biological background noise, in volts.

    The three terms are physically distinct and stay separate in the ledger:

    ``background_source_am``
        RMS current dipole moment (A*m) of spatially white, temporally ``1/f``
        background brain activity.  Passed **through the lead field**, so the
        resulting sensor noise is spatially coloured exactly as real EEG
        background is -- not an isotropic white blob bolted onto the sensors.
    ``sensor_white_v``
        Amplifier + electrode thermal noise, per channel, in V/sqrt(Hz).
    ``line_v``
        Mains pickup amplitude in V, scaled per channel by impedance imbalance.
    """

    background_source_am: float = 5e-9
    background_exponent: float = 1.0
    sensor_white_v_per_rthz: float = 30e-9
    line_v: float = 2e-6
    line_hz: float = 60.0
    line_harmonics: int = 3
    line_amplitude_jitter: float = 0.05

    def sensor_white_variance(self, dt: float) -> float:
        """Variance in V**2 for a sample at rate ``1/dt`` (Nyquist bandwidth)."""
        bw = 0.5 / dt
        return (self.sensor_white_v_per_rthz**2) * bw


@dataclass(frozen=True)
class ArtifactModel:
    """Ocular and muscular artifacts as explicit generative processes.

    Artifacts are *not* nuisance to be silently regressed out: they are part of
    ``O_m`` and their removal is a modelling step with its own residual bias.
    """

    blink_rate_hz: float = 0.25
    blink_amplitude_v: float = 100e-6
    blink_width_s: float = 0.20
    saccade_rate_hz: float = 2.0
    saccade_amplitude_v: float = 20e-6
    muscle_amplitude_v: float = 5e-6
    muscle_band_hz: tuple[float, float] = (20.0, 200.0)
    residual_after_cleaning: float = 0.10
    """Fraction of artifact variance surviving ICA/regression cleaning.

    This is the number that makes artifact removal auditable; it enters the
    ledger as an externally bounded bias, not as zero.
    """

    def ocular_topography(self, sensor_pos: torch.Tensor) -> torch.Tensor:
        """Frontal-maximum topography from an anterior-superior eye-field dipole.

        A cornea-retinal dipole sits *outside* the brain compartment, so it is
        modelled by its scalp topography rather than by pushing it through a
        head model that would refuse it (see
        :class:`~scwbd.observe.leadfield.SphericalHeadModel.potential`).
        """
        p = sensor_pos.to(torch.float64)
        c = p.mean(0)
        rel = p - c
        r = rel.norm(dim=-1).clamp_min(1e-9)
        # anterior (+y in RAS-like frames) and inferior weighting
        w = (rel[:, 1] / r).clamp_min(0.0) ** 2 * torch.exp(
            -((rel[:, 2] / r).clamp_min(0.0)) * 2.0
        )
        return w / w.abs().max().clamp_min(1e-12)

    def muscle_topography(self, sensor_pos: torch.Tensor) -> torch.Tensor:
        """Temporalis / neck maximum: lateral and inferior electrodes."""
        p = sensor_pos.to(torch.float64)
        c = p.mean(0)
        rel = p - c
        r = rel.norm(dim=-1).clamp_min(1e-9)
        lateral = (rel[:, 0] / r).abs()
        inferior = (-rel[:, 2] / r).clamp_min(0.0)
        w = lateral * (0.3 + inferior)
        return w / w.abs().max().clamp_min(1e-12)


