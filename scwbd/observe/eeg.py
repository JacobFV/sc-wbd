"""EEG observation head: source current -> sensor volts on the amplifier clock.

Thesis anchors
--------------
* thesis_contract.tex Sec. 0.3 (T2) --- ``y_E[k] = L(l) x(k dt_E) + eps_E[k]``,
  ``dt_E = 1 ms``.  :meth:`EEGObservationOperator.linear_gaussian` returns
  exactly this pair ``(L, R)`` so the identifiability laboratory consumes the
  same operator the simulator uses.
* body.tex Sec. 7.1 --- "EEG samples need not be downsampled to the fMRI
  repetition time".  :meth:`EEGObservationOperator.observe` reads the latent on
  the *EEG* clock by selection, never by interpolation, and never learns that a
  BOLD head exists.
* body.tex Table ``tab:modalities`` --- EEG dominant bias/variance terms:
  contact location, impedance, conductivity, reference, artifacts,
  coregistration, source non-identifiability.  Every one has a named entry in
  the returned ledger.

Units are volts, always.  The lead field carries V/(A*m); source amplitudes are
current dipole moments in A*m (or A*m/parcel for a parcel-level state).
"""

